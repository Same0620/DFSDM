/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */
  /* The video does this in main's while(1); with FreeRTOS running, main never
     reaches that loop, so the same work happens here in the task instead. */
  for(;;)
  {
    if (DmaRecHalfBuffCplt)
    {
      for (int i = 0; i < AUDIO_REC / 2; i++)
      {
        PlayBuf[i] = RecBuf[i] >> 8;   /* drop the 8 status bits, keep the 24-bit audio */
      }
      DmaRecHalfBuffCplt = 0;
    }
    if (DmaRecBuffCplt)
    {
      for (int i = AUDIO_REC / 2; i < AUDIO_REC; i++)
      {
        PlayBuf[i] = RecBuf[i] >> 8;
      }
      DmaRecBuffCplt = 0;
    }
    osDelay(1);
  }
  /* USER CODE END 5 */
}

